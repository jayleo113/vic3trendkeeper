"""Generates the "Full History Charts" Victoria 3 mod (scripts, GUI, localization, metadata).

Data
  * At game start, on the first monthly pulse after the mod is added, and every 1 January,
    every existing country stores one sample per metric in a country variable
    fhc_<metric>_<slot>, slot = current year - first recorded year (0..SLOTS-1), plus
    fhc_<metric>_first / _last / _prev / _max. A country that is formed, released, becomes
    independent or wins a revolution/secession gets its first sample immediately.
  * Year and slot are found with generated binary searches (~11 + ~8 trigger checks).

GUI - native side panels (vanilla default_block_window_two_lines, created through
gui/scripted_widgets; no vanilla GUI file is overridden):
  * "own" panel: docked on the left like any information panel while no vanilla panel is open;
    it steps aside when one opens and comes back when it closes.
  * "companion" panel: while the country panel is open, the charts of THAT country appear right
    next to it - click any country on the map and the charts follow.
  * Entry points: CMF sidebar button (when [1.13] Community Mod Framework is loaded), a
    draggable round button, Ctrl+Shift+G; the panel's own close button / ESC closes it.
  * One linear time axis shared by all 14 metric pages; hidden pages are not updated.

Run:  python generate.py   (writes ../full_history_charts)
"""
