def search_tree(lo, hi, cond, leaf, indent):
    """Nested if/else picking the largest k in [lo, hi] with cond(k) true (cond monotone)."""
    t = '\t' * indent
    if lo == hi:
        return [f'{t}{leaf(lo)}']
    mid = (lo + hi + 1) // 2
    return ([f'{t}if = {{', f'{t}\tlimit = {{ {cond(mid)} }}'] + search_tree(mid, hi, cond, leaf, indent + 1) +
            [f'{t}}}', f'{t}else = {{'] + search_tree(lo, mid - 1, cond, leaf, indent + 1) + [f'{t}}}'])


def gen_effects():
    L = ['# Generated by fhc_tools/generate.py - do not edit by hand.', '']
    L.append(f'{v("compute_year")} = {{  # binary search on game_date ({YEAR_MIN}..{YEAR_MAX})')
    L += search_tree(YEAR_MIN, YEAR_MAX, lambda y: f'game_date >= {y}.1.1',
                     lambda y: f'set_global_variable = {{ name = {v("cur_year")} value = {y} }}', 1)
    L += ['}', '']
    L.append(f'{v("record_year")} = {{')
    L.append(f'\t{v("compute_year")} = yes')
    L.append(f'\tif = {{ limit = {{ NOT = {{ has_global_variable = {v("start_year")} }} }}')
    L.append(f'\t\tset_global_variable = {{ name = {v("start_year")} value = global_var:{v("cur_year")} }}')
    L.append('\t}')
    L.append(f'\tset_global_variable = {{ name = {v("slot")} value = global_var:{v("cur_year")} }}')
    L.append(f'\tchange_global_variable = {{ name = {v("slot")} subtract = global_var:{v("start_year")} }}')
    L.append(f'\tif = {{  # full after {SLOTS} years: keep the first {SLOTS}')
    L.append(f'\t\tlimit = {{ global_var:{v("slot")} >= 0 global_var:{v("slot")} < {SLOTS} }}')
    L += search_tree(0, SLOTS - 1, lambda s: f'global_var:{v("slot")} >= {s}',
                     lambda s: f'{v("record_slot")} = {{ S = {s} }}', 2)
    L += ['\t}', '}', '']
    L.append(f'{v("record_slot")} = {{')
    L.append(f'\tset_global_variable = {{ name = {v("year")}_$S$ value = global_var:{v("cur_year")} }}')
    L.append(f'\tset_global_variable = {{ name = {v("last_slot")} value = $S$ }}')
    L.append(f'\tevery_country = {{ {v("record_country")} = {{ S = $S$ }} }}')
    L += ['}', '']
    # a single (new) country, into the current year's slot - used by the country-birth on_actions
    L.append(f'{v("record_one")} = {{  # scope: country')
    L.append(f'\tif = {{')
    L.append(f'\t\tlimit = {{ has_global_variable = {v("last_slot")} global_var:{v("last_slot")} >= 0 '
             f'global_var:{v("last_slot")} < {SLOTS} }}')
    L += search_tree(0, SLOTS - 1, lambda s: f'global_var:{v("last_slot")} >= {s}',
                     lambda s: f'{v("record_country")} = {{ S = {s} }}', 2)
    L += ['\t}', '}', '']
    L.append(f'{v("record_country")} = {{')
    for key, val, *_ in METRICS:
        expr = '{ value = gdp divide = { value = total_population min = 1 } }' if val is None else val
        L.append(f'\tset_variable = {{ name = {v(key)}_$S$ value = {expr} }}')
    # previous year's value: only when this is a new slot (several records may hit the same year)
    L.append(f'\tif = {{ limit = {{ has_variable = {v("lslot")} var:{v("lslot")} < $S$ }}')
    for key, *_ in METRICS:
        L.append(f'\t\tif = {{ limit = {{ has_variable = {v(key)}_last }} '
                 f'set_variable = {{ name = {v(key)}_prev value = var:{v(key)}_last }} }}')
    L.append('\t}')
    L.append(f'\tset_variable = {{ name = {v("lslot")} value = $S$ }}')
    for key, *_ in METRICS:
        cur = f'var:{v(key)}_$S$'
        L.append(f'\tset_variable = {{ name = {v(key)}_last value = {cur} }}')
        L.append(f'\tif = {{ limit = {{ NOT = {{ has_variable = {v(key)}_first }} }} set_variable = {{ name = {v(key)}_first value = {cur} }} }}')
        L.append(f'\tif = {{ limit = {{ OR = {{ NOT = {{ has_variable = {v(key)}_max }} {cur} > var:{v(key)}_max }} }} '
                 f'set_variable = {{ name = {v(key)}_max value = {cur} }} }}')
    L += ['}', '']
    return '\n'.join(L)


