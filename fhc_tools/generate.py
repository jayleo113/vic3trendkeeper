# ------------------------------------------------------------------ GUI
def color(c, a=1.0):
    return f'{{ {c[0]:.2f} {c[1]:.2f} {c[2]:.2f} {a:.2f} }}'


def var(key, name):
    return f"Country.MakeScope.Var('{v(key)}_{name}')"


def year_set(s):
    return f"GetGlobalVariable('{v('year')}_{s}').IsSet"


def metric_selected(i, key):
    sel = f"GetVariableSystem.HasValue('{v('metric')}', '{key}')"
    return f"Or({sel}, Not(GetVariableSystem.Exists('{v('metric')}')))" if i == 0 else sel


def gui_metric_page(i, key, col, fmt):
    mx, first, last, prev = (var(key, n) for n in ('max', 'first', 'last', 'prev'))
    zero = "'(CFixedPoint)0'"

    def chg(a, b):
        return f'Divide_CFixedPoint(Subtract_CFixedPoint({a}.GetValue, {b}.GetValue), {b}.GetValue)'

    def tb(x, y, vis, text, size=13):
        return (['\t\t\ttextbox = {', f'\t\t\t\tposition = {{ {x} {y} }}', '\t\t\t\tautoresize = yes',
                 f'\t\t\t\tfontsize = {size}'] + ([f'\t\t\t\tvisible = "[{vis}]"'] if vis else []) +
                [f'\t\t\t\t{text}', '\t\t\t}'])

    def axis(y, text, vis):
        return (['\t\t\ttextbox = {', f'\t\t\t\tposition = {{ 0 {y} }}', f'\t\t\t\tsize = {{ {AXIS_W - 6} 16 }}',
                 '\t\t\t\talign = right|nobaseline', '\t\t\t\tfontsize = 12', f'\t\t\t\traw_text = "{text}"'] +
                ([f'\t\t\t\tvisible = "[{vis}]"'] if vis else []) + ['\t\t\t}'])

    out = [f'\t\twidget = {{  # page: {key}',
           f'\t\t\tsize = {{ {AXIS_W + CHART_W} {CHART_Y + CHART_H + 24} }}',
           f'\t\t\tvisible = "[{metric_selected(i, key)}]"']
    out += tb(0, 0, f'{mx}.IsSet',
              f"raw_text = \"[Localize('FHC_FIRST')] #v [{first}.GetValue|{fmt}]#!　"
              f"[Localize('FHC_MAX')] #v [{mx}.GetValue|{fmt}]#!　"
              f"[Localize('FHC_LATEST')] #v [{last}.GetValue|{fmt}]#!\"", 14)
    out += tb(0, 21, f'And({prev}.IsSet, GreaterThan_CFixedPoint({prev}.GetValue, {zero}))',
              f"raw_text = \"[Localize('FHC_YOY')] [{chg(last, prev)}|+=1%]\"")
    out += tb(200, 21, f'And({first}.IsSet, GreaterThan_CFixedPoint({first}.GetValue, {zero}))',
              f"raw_text = \"[Localize('FHC_SINCE_FIRST')] [{chg(last, first)}|+=0%]\"")
    out += tb(0, 0, f'Not({mx}.IsSet)', 'text = "FHC_NO_DATA"', 13)
    out += axis(CHART_Y, f'[{mx}.GetValue|{fmt}]', f'{mx}.IsSet')
    out += axis(CHART_Y + CHART_H // 2 - 8, f"[Multiply_CFixedPoint({mx}.GetValue, '(CFixedPoint)0.5')|{fmt}]", f'{mx}.IsSet')
    out += axis(CHART_Y + CHART_H - 16, '0', None)
    # one cell per recorded YEAR (global): every page shares one linear time axis, a year without
    # data for this country/metric stays an empty cell instead of being squeezed out
    out += ['\t\t\thbox = {', f'\t\t\t\tposition = {{ {AXIS_W} {CHART_Y} }}', f'\t\t\t\tsize = {{ {CHART_W} {CHART_H} }}',
            f'\t\t\t\tspacing = {GAP}', '\t\t\t\tignoreinvisible = yes']
    for s in range(SLOTS):
        cur = var(key, s)
        out += ['\t\t\t\twidget = {', '\t\t\t\t\tusing = fhc_bar_cell', f'\t\t\t\t\tvisible = "[{year_set(s)}]"',
                '\t\t\t\t\tprogressbar = {', '\t\t\t\t\t\tsize = { 100% 100% }', '\t\t\t\t\t\tusing = fhc_bar_style',
                f'\t\t\t\t\t\tvisible = "[{cur}.IsSet]"',
                f"\t\t\t\t\t\traw_tooltip = \"#T [GetGlobalVariable('{v('year')}_{s}').GetValue|0]#!\\n[{cur}.GetValue|{fmt}]\"",
                f'\t\t\t\t\t\tcolor = {color(col)}',
                f'\t\t\t\t\t\tmax = "[FixedPointToFloat({mx}.GetValue)]"',
                f'\t\t\t\t\t\tvalue = "[FixedPointToFloat({cur}.GetValue)]"', '\t\t\t\t\t}', '\t\t\t\t}']
    out += ['\t\t\t\texpand = {}', '\t\t\t}', '\t\t}']
    return '\n'.join(out)


def gui_year_labels():
    """One shared row of year labels, laid out exactly like the bar cells."""
    out = ['\t\thbox = {', f'\t\t\tposition = {{ {AXIS_W} {CHART_Y + CHART_H + 3} }}', f'\t\t\tsize = {{ {CHART_W} 16 }}',
           f'\t\t\tspacing = {GAP}', '\t\t\tignoreinvisible = yes']
    for s in range(SLOTS):
        out += ['\t\t\twidget = {', '\t\t\t\tusing = fhc_label_cell', f'\t\t\t\tvisible = "[{year_set(s)}]"']
        if s % 10 == 0:
            out += ['\t\t\t\ttextbox = {', '\t\t\t\t\tautoresize = yes', '\t\t\t\t\tfontsize = 11',
                    f"\t\t\t\t\traw_text = \"[GetGlobalVariable('{v('year')}_{s}').GetValue|0]\"", '\t\t\t\t}']
        out += ['\t\t\t}']
    out += ['\t\t\texpand = {}', '\t\t}']
    return '\n'.join(out)


def gui_metric_tabs():
    rows = (len(METRICS) + TAB_COLS - 1) // TAB_COLS
    out = ['\t\t\twidget = {', f'\t\t\t\tsize = {{ {TAB_COLS * (TAB_W + 4)} {rows * 32 + 4} }}']
    for i, (key, _val, col_rgb, *_r) in enumerate(METRICS):
        r, c = divmod(i, TAB_COLS)
