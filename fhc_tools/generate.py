def write(rel, text, bom=True):
    p = ROOT / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    data = text.replace('\r\n', '\n').encode('utf-8')
    p.write_bytes((b'\xef\xbb\xbf' if bom else b'') + data)
    return p


def v(name):
    return f'{P}_{name}'


